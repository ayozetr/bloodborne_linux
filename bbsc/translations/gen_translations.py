"""bbport: makes bbsc/emulator/src/core/bbsc_translations.inc from the translations of BBSC's texts.

Each <language>.json here maps BBSC's English text (as written in its C++ sources, "\\n" for a line
break; "{boss}" where a text names one boss with <?npcNameId@N?>) to that language. The .inc is
the table core/bbsc_i18n.cpp looks them up in; run this after changing a .json:

    python3 bbsc/translations/gen_translations.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'emulator/src/core/bbsc_translations.inc'
# The column order of bbsc_i18n.cpp's Language.
LANGUAGES = ('es', 'fr', 'de', 'it', 'pt', 'ru')
TAGS = ('<?joinName?>', '<?hostName?>', '<?deadName?>', '<?leaveName?>', '{boss}')


def literal(text):
    """A C++ u"" literal of text, whose line breaks are already written as \\n."""
    return 'u"' + text.replace('\\', '\\\\').replace('\\\\n', '\\n').replace('"', '\\"') + '"'


def main():
    tables = {lang: json.loads((HERE / f'{lang}.json').read_text(encoding='utf-8'))
              for lang in LANGUAGES}
    english = list(tables[LANGUAGES[0]])
    lines = ['// Generated by bbsc/translations/gen_translations.py from bbsc/translations/*.json - do not',
             '// edit. {english, {' + ', '.join(LANGUAGES) + '}}']
    for text in english:
        if '\n' in text:  # not one of BBSC's texts
            continue
        row = []
        for lang in LANGUAGES:
            translated = tables[lang].get(text)
            if translated is None or '\n' in translated:
                raise SystemExit(f'{lang}: no translation of {text!r}')
            for tag in TAGS:
                if text.count(tag) != translated.count(tag):
                    raise SystemExit(f'{lang}: {tag} differs in {text!r}')
            row.append(literal(translated))
        lines.append('{' + literal(text) + ', {' + ', '.join(row) + '}},')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUT}: {len(lines) - 2} texts, {len(LANGUAGES)} languages')


if __name__ == '__main__':
    main()
