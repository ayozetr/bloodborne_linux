_language = "ru"


def set_language(choice):
    """choice: one of LANGUAGES or "" (the system's)."""
    global _language
    _language = choice if choice in LANGUAGES else system_language()


def language():
    return _language


def tr(text):
    table = TRANSLATIONS.get(_language)
    if table is None:
        return text
    return table.get(text, EN.get(text, text))

